const accountByCode = new Map(ACCOUNTS.map((a) => [a.code, a]));

function seriesForAccount(code) {
  const a = accountByCode.get(String(code || '').trim());
  return a ? a.series : '8';
}
function categoriesForAccount(code) {
  return seriesForAccount(code) === '7' ? CATEGORIES_7 : CATEGORIES_8;
}
function isValidCategory(accountCode, catCode) {
  const c = String(catCode || '').trim();
  return categoriesForAccount(accountCode).some((x) => x.code === c);
}
function accountName(code) { const a = accountByCode.get(String(code || '').trim()); return a ? a.name : ''; }
function categoryName(code) {
  const c = String(code || '').trim();
  const hit = CATEGORIES_7.concat(CATEGORIES_8).find((x) => x.code === c);
  return hit ? hit.name : '';
}

