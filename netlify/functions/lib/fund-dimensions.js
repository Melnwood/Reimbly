const GENERAL_FUND_CODE = '010000';
// Intacct records the General Fund's project without the leading zeros ('10000'),
// as seen in CedarStone's own upload file; every other fund uses its 6-digit code.
const GENERAL_FUND_PROJECT = '10000';

// Normalize any fund reference to the 6-digit key ('10000' → '010000').
function normCode(code) {
  const m = /(\d+)/.exec(String(code || ''));
  return m ? m[1].padStart(6, '0') : '';
}

// Look up a fund's dimensions. Returns null if the code isn't in the listing.
function dimensionsFor(code) {
  const key = normCode(code);
  const d = DIMENSIONS[key];
  if (!d) return null;
  return {
    name: d[0], dept: d[1], class: d[2], entity: d[3],
    project: key === GENERAL_FUND_CODE ? GENERAL_FUND_PROJECT : key,
  };
}

module.exports = { DIMENSIONS, GENERAL_FUND_CODE, GENERAL_FUND_PROJECT, normCode, dimensionsFor };
